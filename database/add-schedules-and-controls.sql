-- Migración aditiva: no borra materias, descripciones ni asistencias anteriores.
-- Las materias existentes quedan con fechas NULL hasta que su dueño las complete.
BEGIN;
ALTER TABLE materias ADD COLUMN IF NOT EXISTS fecha_inicio DATE;
ALTER TABLE materias ADD COLUMN IF NOT EXISTS fecha_fin DATE;
ALTER TABLE materias ADD COLUMN IF NOT EXISTS porcentaje_asistencia_minima NUMERIC(5,2) NOT NULL DEFAULT 75
    CHECK (porcentaje_asistencia_minima BETWEEN 0 AND 100);
CREATE TABLE IF NOT EXISTS horarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    materia_id BIGINT NOT NULL REFERENCES materias(id),
    dia_semana VARCHAR(15) NOT NULL CHECK (dia_semana IN ('LUNES','MARTES','MIERCOLES','JUEVES','VIERNES','SABADO','DOMINGO')),
    hora_inicio TIME NOT NULL, hora_fin TIME NOT NULL,
    controles_asistencia INTEGER NOT NULL CHECK (controles_asistencia IN (1,2)),
    CHECK (hora_inicio < hora_fin)
);
CREATE INDEX IF NOT EXISTS idx_horarios_materia ON horarios(materia_id);
CREATE TABLE IF NOT EXISTS controles_asistencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    horario_id BIGINT NOT NULL REFERENCES horarios(id),
    fecha DATE NOT NULL, numero INTEGER NOT NULL CHECK (numero IN (1,2)),
    estado VARCHAR(15) NOT NULL CHECK (estado IN ('PRESENTE','AUSENTE','JUSTIFICADA')),
    CONSTRAINT uk_control_horario_fecha_numero UNIQUE (horario_id, fecha, numero)
);
CREATE TABLE IF NOT EXISTS fechas_sin_cursada (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    materia_id BIGINT NOT NULL REFERENCES materias(id), fecha DATE NOT NULL,
    CONSTRAINT uk_fecha_sin_cursada UNIQUE (materia_id, fecha)
);
COMMIT;
