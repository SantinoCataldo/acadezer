-- Run once against an EMPTY, separate academic database. No DROP/ALTER/data migration.
BEGIN;
CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'STUDENT',
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_usuarios_role CHECK (role IN ('STUDENT', 'ADMIN'))
);
CREATE TABLE materias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    descripcion VARCHAR(2000),
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id)
);
CREATE TABLE apuntes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(200) NOT NULL,
    contenido VARCHAR(20000) NOT NULL,
    materia_id BIGINT NOT NULL REFERENCES materias(id)
);
CREATE TABLE pendientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(200) NOT NULL,
    descripcion VARCHAR(2000),
    fecha_limite DATE,
    completado BOOLEAN NOT NULL DEFAULT FALSE,
    materia_id BIGINT NOT NULL REFERENCES materias(id)
);
CREATE TABLE evaluaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(200) NOT NULL,
    fecha DATE NOT NULL,
    calificacion NUMERIC(4,2) CHECK (calificacion BETWEEN 0 AND 10),
    materia_id BIGINT NOT NULL REFERENCES materias(id)
);
CREATE TABLE asistencias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL,
    estado VARCHAR(15) NOT NULL CHECK (estado IN ('PRESENTE', 'AUSENTE', 'JUSTIFICADA')),
    materia_id BIGINT NOT NULL REFERENCES materias(id),
    CONSTRAINT uk_asistencia_materia_fecha UNIQUE (materia_id, fecha)
);
CREATE INDEX idx_materias_usuario ON materias(usuario_id);
CREATE INDEX idx_apuntes_materia ON apuntes(materia_id);
CREATE INDEX idx_pendientes_materia ON pendientes(materia_id);
CREATE INDEX idx_evaluaciones_materia ON evaluaciones(materia_id);
COMMIT;
