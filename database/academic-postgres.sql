-- Run once against an EMPTY, separate academic database. No DROP/ALTER/data migration.
BEGIN;
CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'STUDENT',
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_usuarios_role CHECK (role IN ('STUDENT', 'ADMIN'))
);
CREATE TABLE materias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    fecha_inicio DATE,
    fecha_fin DATE,
    porcentaje_asistencia_minima NUMERIC(5,2) NOT NULL DEFAULT 75 CHECK (porcentaje_asistencia_minima BETWEEN 0 AND 100),
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id)
);
CREATE TABLE refresh_tokens (
    token_hash VARCHAR(64) PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_refresh_tokens_expires_at ON refresh_tokens(expires_at);
CREATE TABLE horarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    materia_id BIGINT NOT NULL REFERENCES materias(id),
    dia_semana VARCHAR(15) NOT NULL CHECK (dia_semana IN ('LUNES','MARTES','MIERCOLES','JUEVES','VIERNES','SABADO','DOMINGO')),
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    controles_asistencia INTEGER NOT NULL CHECK (controles_asistencia IN (1,2)),
    CHECK (hora_inicio < hora_fin)
);
CREATE INDEX idx_horarios_materia ON horarios(materia_id);
CREATE TABLE controles_asistencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    horario_id BIGINT NOT NULL REFERENCES horarios(id),
    fecha DATE NOT NULL,
    numero INTEGER NOT NULL CHECK (numero IN (1,2)),
    estado VARCHAR(15) NOT NULL CHECK (estado IN ('PRESENTE','AUSENTE','JUSTIFICADA')),
    CONSTRAINT uk_control_horario_fecha_numero UNIQUE (horario_id, fecha, numero)
);
CREATE TABLE fechas_sin_cursada (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    materia_id BIGINT NOT NULL REFERENCES materias(id),
    fecha DATE NOT NULL,
    CONSTRAINT uk_fecha_sin_cursada UNIQUE (materia_id, fecha)
);
CREATE TABLE apuntes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(200) NOT NULL,
    contenido VARCHAR(20000) NOT NULL,
    materia_id BIGINT NOT NULL REFERENCES materias(id)
);
CREATE TABLE pendientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(200) NOT NULL,
    descripcion VARCHAR(2000),
    fecha_limite DATE,
    completado BOOLEAN NOT NULL DEFAULT FALSE,
    materia_id BIGINT NOT NULL REFERENCES materias(id)
);
CREATE TABLE evaluaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(200) NOT NULL,
    fecha DATE NOT NULL,
    calificacion NUMERIC(4,2) CHECK (calificacion BETWEEN 0 AND 10),
    materia_id BIGINT NOT NULL REFERENCES materias(id)
);
CREATE TABLE asistencias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL,
    estado VARCHAR(15) NOT NULL CHECK (estado IN ('PRESENTE', 'AUSENTE', 'JUSTIFICADA')),
    materia_id BIGINT NOT NULL REFERENCES materias(id),
    CONSTRAINT uk_asistencia_materia_fecha UNIQUE (materia_id, fecha)
);
CREATE INDEX idx_materias_usuario ON materias(usuario_id);
CREATE INDEX idx_apuntes_materia ON apuntes(materia_id);
CREATE INDEX idx_pendientes_materia ON pendientes(materia_id);
CREATE INDEX idx_evaluaciones_materia ON evaluaciones(materia_id);
COMMIT;
